package io.mateu.modux.modeldrivengenerator.e2e;

import io.mateu.modux.modeldrivengenerator.application.usecases.project.generatecode.GenerateCodeCommand;
import io.mateu.modux.modeldrivengenerator.application.usecases.project.generatecode.GenerateCodeUseCase;
import io.mateu.modux.modeldrivengenerator.infra.out.persistence.file.CommonFileRepository;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.util.FileSystemUtils;

import java.nio.file.Files;
import java.nio.file.Path;

import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The scripts, README and e2e suite generated into a project speak the project's language:
 * English unless it says Spanish. The entradas store declares Spanish; a copy of it switched
 * to English must come out in English. Generation only.
 */
@SpringBootTest
class GeneratedOpsLanguageTest {

    static final Path STORE = Path.of("src/test/resources/examples/entradas").toAbsolutePath();

    static {
        System.setProperty("modux.model-file", STORE.toString());
    }

    @Autowired
    GenerateCodeUseCase generateCodeUseCase;

    @Autowired
    CommonFileRepository repository;

    @Test
    void a_spanish_project_keeps_its_spanish_scripts() throws Exception {
        repository.loadFrom(STORE.toString());
        var out = Files.createTempDirectory("modux-ops-es");
        generateCodeUseCase.handle(new GenerateCodeCommand("entradas", out.toString(), null, false));

        var up = Files.readString(out.resolve("up.sh"));
        assertTrue(up.contains("Levanta el sistema completo en local"), up);
        assertTrue(up.contains("Sistema arriba:"), up);
        assertTrue(up.contains("esperando a postgres"), up);
        assertTrue(up.contains("Para pararlo todo: ./down.sh"), up);
        assertTrue(Files.readString(out.resolve("down.sh")).contains("Sistema parado (los logs quedan en .up-*.log)."));
        var readme = Files.readString(out.resolve("README.md"));
        assertTrue(readme.contains("Proyecto generado por [modux]"), readme);
        assertTrue(readme.contains("## Servicios"), readme);
        assertTrue(Files.readString(out.resolve("e2e/pom.xml")).contains("Suite Playwright-Java que conduce las apps"));
    }

    @Test
    void an_english_project_gets_english_scripts() throws Exception {
        var store = Files.createTempDirectory("modux-ops-store");
        FileSystemUtils.copyRecursively(STORE, store);
        var project = store.resolve("projects/entradas.yaml");
        Files.writeString(project, Files.readString(project).replace("defaultLocale: \"es\"", "defaultLocale: \"en\""));
        repository.loadFrom(store.toString());
        var out = Files.createTempDirectory("modux-ops-en");
        try {
            generateCodeUseCase.handle(new GenerateCodeCommand("entradas", out.toString(), null, false));

            var up = Files.readString(out.resolve("up.sh"));
            assertTrue(up.startsWith("#!/bin/sh"), up);
            assertTrue(up.contains("Starts the whole system locally"), up);
            assertTrue(up.contains("System up:"), up);
            assertTrue(up.contains("waiting for postgres"), up);
            assertTrue(up.contains("To stop everything: ./down.sh"), up);
            for (var spanish : java.util.List.of("Levanta", "esperando", "Sistema arriba", "Para pararlo", "GENERADO")) {
                assertFalse(up.contains(spanish), spanish + " leaked into up.sh:\n" + up);
            }
            var down = Files.readString(out.resolve("down.sh"));
            assertTrue(down.startsWith("#!/bin/sh"), down);
            assertTrue(down.contains("System stopped (the logs stay in .up-*.log)."), down);
            var readme = Files.readString(out.resolve("README.md"));
            assertTrue(readme.contains("Project generated by [modux]"), readme);
            assertTrue(readme.contains("## Services"), readme);
            assertFalse(readme.contains("Regenerar"), readme);
            var pom = Files.readString(out.resolve("e2e/pom.xml"));
            assertTrue(pom.startsWith("<?xml"), pom);
            assertTrue(pom.contains("Playwright-Java suite that drives the apps"), pom);
            assertTrue(Files.readString(out.resolve("e2e/src/test/java/e2e/BaseE2eTest.java"))
                    .contains("playwright install chromium failed"));
            var yaml = Files.readString(out.resolve("gateway/src/main/resources/application.yaml"));
            assertTrue(yaml.contains("the routes come from the model"), yaml);
            assertFalse(yaml.contains("la shell (todo lo demás)"), yaml);
        } finally {
            repository.loadFrom(STORE.toString());
        }
    }
}
