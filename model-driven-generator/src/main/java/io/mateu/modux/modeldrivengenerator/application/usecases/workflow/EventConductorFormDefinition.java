package io.mateu.modux.modeldrivengenerator.application.usecases.workflow;

import io.mateu.modux.modeldrivengenerator.infra.out.persistence.file.ModelFieldEntity;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.function.Function;

/**
 * A page's model as the EventConductor form a human task presents.
 *
 * <p>What the person submits becomes the process's variables, named by each field's id — so the
 * id is the field's NAME (what the next step's use case reads by), not its element id. An enum is
 * a select with its values; a required field says so.
 */
public final class EventConductorFormDefinition {

    private EventConductorFormDefinition() {}

    /**
     * @param pageName   the page the form comes from (its id is {@link EventConductorWorkflowDefinition#formId})
     * @param fields     the page model's fields
     * @param enumValues the values of an enum, by its id
     */
    public static Map<String, Object> of(String pageName, List<ModelFieldEntity> fields,
                                         Function<String, List<String>> enumValues) {
        var form = new LinkedHashMap<String, Object>();
        form.put("id", EventConductorWorkflowDefinition.formId(pageName));
        form.put("name", pageName);
        form.put("description", "Generated by Modux from page " + pageName);
        var out = new ArrayList<Map<String, Object>>();
        for (var f : fields == null ? List.<ModelFieldEntity>of() : fields) {
            var field = new LinkedHashMap<String, Object>();
            field.put("id", f.name());
            field.put("label", f.label() != null && !f.label().isBlank() ? f.label() : f.name());
            var values = f.enumId() != null && !f.enumId().isBlank() ? enumValues.apply(f.enumId()) : null;
            if (values != null && !values.isEmpty()) {
                field.put("dataType", "string");
                field.put("stereotype", "select");
                field.put("options", values.stream().map(v -> Map.of("value", v)).toList());
            } else {
                field.put("dataType", dataType(f));
            }
            if (f.validations() != null && f.validations().stream()
                    .anyMatch(v -> List.of("NotNull", "NotEmpty", "NotBlank").contains(String.valueOf(v.type())))) {
                field.put("required", true);
            }
            out.add(field);
        }
        form.put("fields", out);
        return form;
    }

    private static String dataType(ModelFieldEntity f) {
        if (f.type() == null) return "string";
        return switch (f.type()) {
            case integer -> "integer";
            case number -> "number";
            case money -> "money";
            case bool -> "bool";
            case date -> "date";
            case time -> "time";
            case dateTime -> "dateTime";
            case file -> "file";
            case array -> "array";
            default -> "string";
        };
    }
}
